"""Writes src117/gen/cp949.inc: Korean CP949 (Windows' code page 949, KS X 1001 with Unified
Hangul Code) as a table of Unicode code points, for map text (port_maptext.cpp).

The table is indexed by a lead byte 0x81 to 0xFE and a trail byte 0x41 to 0xFE; an entry is the
pair's code point, 0 for a pair that makes no character. Made from Python's cp949 codec, which
follows Windows' table. A standard code page, not anything of the game's.

  python tools/gen_cp949.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'src117' / 'gen' / 'cp949.inc'
LEAD_FIRST, LEAD_LAST = 0x81, 0xFE
TRAIL_FIRST, TRAIL_LAST = 0x41, 0xFE


def main():
    rows = []
    count = 0
    for lead in range(LEAD_FIRST, LEAD_LAST + 1):
        row = []
        for trail in range(TRAIL_FIRST, TRAIL_LAST + 1):
            cp = 0
            try:
                s = bytes([lead, trail]).decode('cp949')
                if len(s) == 1 and ord(s) >= 0x80:
                    cp = ord(s)
            except UnicodeDecodeError:
                pass
            count += cp != 0
            row.append(cp)
        rows.append(row)
    lines = [
        '// cp949.inc -- generated by tools/gen_cp949.py: Korean CP949 as Unicode code points, by lead',
        f'// byte 0x{LEAD_FIRST:02X} to 0x{LEAD_LAST:02X} and trail byte 0x{TRAIL_FIRST:02X} to 0x{TRAIL_LAST:02X}; 0 for no character. {count} characters.',
        f'static const unsigned short kCp949[{LEAD_LAST - LEAD_FIRST + 1}][{TRAIL_LAST - TRAIL_FIRST + 1}] = {{',
    ]
    for lead, row in zip(range(LEAD_FIRST, LEAD_LAST + 1), rows):
        lines.append(f'  {{  // 0x{lead:02X}')
        for i in range(0, len(row), 16):
            lines.append('    ' + ','.join(str(v) for v in row[i:i + 16]) + ',')
        lines.append('  },')
    lines.append('};')
    OUT.write_bytes(('\r\n'.join(lines) + '\r\n').encode('ascii'))
    print(f'{OUT}: {count} characters')


if __name__ == '__main__':
    main()
